import os
import glob
import numpy as np
from scipy.interpolate import griddata

def read_xyz(filepath):
    atoms = []
    grid = []
    parsing_atoms = False
    parsing_grid = False
    
    with open(filepath, 'r') as f:
        for line in f:
            line = line.strip()
            if not line: continue
            if line.startswith('[Atoms]'):
                parsing_atoms = True
                parsing_grid = False
                continue
            elif line.startswith('[Grid]'):
                parsing_atoms = False
                parsing_grid = True
                continue
            
            parts = line.split()
            if parsing_atoms:
                # O 1 8 0.0 0.0 0.0
                # parts: Element, Index, Z, X, Y, Z
                atomic_num = float(parts[2])
                x, y, z = float(parts[3]), float(parts[4]), float(parts[5])
                atoms.append((atomic_num, x, y, z))
            elif parsing_grid:
                # 1 x y z
                x, y, z = float(parts[1]), float(parts[2]), float(parts[3])
                grid.append((x, y, z))
                
    return np.array(atoms), np.array(grid)

def write_cube(filepath, atoms, origin, grid_x, grid_y, grid_z, data):
    with open(filepath, 'w') as f:
        f.write("Generated by convert_to_cube.py\n")
        f.write("Electron density\n")
        
        n_atoms = len(atoms)
        f.write(f"{n_atoms:5d} {origin[0]:12.6f} {origin[1]:12.6f} {origin[2]:12.6f}\n")
        
        nx, ny, nz = data.shape
        dx = grid_x[1] - grid_x[0] if nx > 1 else 0
        dy = grid_y[1] - grid_y[0] if ny > 1 else 0
        dz = grid_z[1] - grid_z[0] if nz > 1 else 0
        
        f.write(f"{nx:5d} {dx:12.6f} {0.0:12.6f} {0.0:12.6f}\n")
        f.write(f"{ny:5d} {0.0:12.6f} {dy:12.6f} {0.0:12.6f}\n")
        f.write(f"{nz:5d} {0.0:12.6f} {0.0:12.6f} {dz:12.6f}\n")
        
        for atom in atoms:
            Z, x, y, z = atom
            charge = Z # Approximate point charge
            f.write(f"{int(Z):5d} {charge:12.6f} {x:12.6f} {y:12.6f} {z:12.6f}\n")
        
        # Write data (Z is fastest changing index in cube files)
        for ix in range(nx):
            for iy in range(ny):
                count = 0
                for iz in range(nz):
                    f.write(f"{data[ix, iy, iz]:13.5E}")
                    count += 1
                    if count % 6 == 0:
                        f.write("\n")
                        count = 0
                if count != 0:
                    f.write("\n")

def main():
    base_dir = "/home/paritosh/Desktop/IIT_BHILAI/sem6/UGQ301/water/water_x.out_tdscf_rvl_FILES"
    xyz_file = os.path.join(base_dir, "rvlab.tdscf.xyz")
    
    print("Reading atoms and grid...")
    atoms, unstructured_grid = read_xyz(xyz_file)
    
    print(f"Loaded {len(atoms)} atoms and {len(unstructured_grid)} grid points.")
    
    # Define uniform Cartesian grid
    pad = 3.0 # Padding around the molecule in Bohr
    min_bounds = unstructured_grid.min(axis=0) - pad
    max_bounds = unstructured_grid.max(axis=0) + pad
    
    spacing = 0.3 # Resolution in Bohr (approx 0.15 Angstrom)
    
    grid_x = np.arange(min_bounds[0], max_bounds[0], spacing)
    grid_y = np.arange(min_bounds[1], max_bounds[1], spacing)
    grid_z = np.arange(min_bounds[2], max_bounds[2], spacing)
    
    print(f"Regular grid dimensions: {len(grid_x)} x {len(grid_y)} x {len(grid_z)} voxels")
    
    X, Y, Z = np.meshgrid(grid_x, grid_y, grid_z, indexing='ij')
    
    # Get list of rho files
    rho_files = sorted(glob.glob(os.path.join(base_dir, "rvlab.tdscf.rho.*")))
    
    # Trim to strictly the first 100 timestamps for initialization
    rho_files = rho_files[:100]
    
    out_dir = "/home/paritosh/Desktop/IIT_BHILAI/sem6/UGQ301/water/cube_files"
    os.makedirs(out_dir, exist_ok=True)
    
    print("Loading baseline density from rvlab.tdscf.rho.00000...")
    baseline_raw = np.loadtxt(rho_files[0])
    if len(baseline_raw.shape) == 2:
        baseline_density = baseline_raw[:, 1]
    else:
        baseline_density = baseline_raw
    
    print(f"Starting interpolation for {len(rho_files)} frames...")
    
    for i, rho_file in enumerate(rho_files):
        # Progress indication
        print(f"Processing frame {i+1}/{len(rho_files)}: {os.path.basename(rho_file)}")
        
        # Read scalar density field
        density = np.loadtxt(rho_file)
        if len(density.shape) == 2:
            density_vals = density[:, 1]
        else:
            density_vals = density
            
        # Calculate density difference (delta rho)
        delta_density = density_vals - baseline_density
            
        # Interpolate scattered grid points to uniform grid
        # Method 'linear' is robust for reasonably dense unstructured points
        #grid_density = griddata(unstructured_grid, delta_density, (X, Y, Z), method='linear', fill_value=0.0)
        # Normalize + amplify
        delta_density = delta_density / (np.max(np.abs(delta_density)) + 1e-12)
        delta_density *= 20

        # Use nearest to preserve structure
        grid_density = griddata(
            unstructured_grid,
            delta_density,
            (X, Y, Z),
            method='nearest',
            fill_value=0.0
        )
        out_name = f"frame_{i:03d}.cube"
        out_path = os.path.join(out_dir, out_name)
        
        origin = (grid_x[0], grid_y[0], grid_z[0])
        write_cube(out_path, atoms, origin, grid_x, grid_y, grid_z, grid_density)
        
    print(f"Done! Cubification completed and files built at {out_dir}")

if __name__ == "__main__":
    main()
